-- Module platform : journal d'audit, notifications, paramètres, messages de contact.
CREATE TABLE platform_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT,
    actor_role VARCHAR(24),
    action VARCHAR(80) NOT NULL,
    entity VARCHAR(40),
    entity_id VARCHAR(80),
    details VARCHAR(4000),
    ip VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_platform_audit_created ON platform_audit_logs(created_at DESC);
CREATE INDEX idx_platform_audit_action ON platform_audit_logs(action);

CREATE TABLE platform_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    type VARCHAR(40) NOT NULL,
    title VARCHAR(200) NOT NULL,
    body VARCHAR(1000),
    link VARCHAR(200),
    read_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_platform_notifications_user ON platform_notifications(user_id, id DESC);

CREATE TABLE platform_settings (
    setting_key VARCHAR(80) PRIMARY KEY,
    setting_value VARCHAR(8000) NOT NULL,
    description VARCHAR(500),
    updated_by BIGINT,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE platform_contact_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(120),
    phone VARCHAR(30),
    subject VARCHAR(150) NOT NULL,
    message VARCHAR(3000) NOT NULL,
    handled BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
