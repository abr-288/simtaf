-- Module providers : profils prestataires et services/tarifs proposés.
CREATE TABLE providers_profiles (
    user_id BIGINT PRIMARY KEY,
    category VARCHAR(30) NOT NULL DEFAULT 'autre',
    description VARCHAR(800),
    zone VARCHAR(100),
    available BOOLEAN NOT NULL DEFAULT TRUE,
    verified BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE providers_services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL,
    label VARCHAR(150) NOT NULL,
    category VARCHAR(30) NOT NULL DEFAULT 'autre',
    unit_cost INTEGER NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
    unit VARCHAR(40) NOT NULL DEFAULT 'prestation',
    description VARCHAR(400),
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE INDEX idx_providers_services_provider ON providers_services(provider_id);
