-- Transactions de paiement en ligne (Mobile Money) : encaissements des clients et reversements aux prestataires.
-- Une transaction reste « pending » jusqu'à la confirmation du fournisseur (webhook vérifié, puis statut relu chez lui).
CREATE TABLE giving_payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES giving_payments(id),
    direction VARCHAR(4) NOT NULL,
    provider VARCHAR(20) NOT NULL,
    provider_ref VARCHAR(100),
    amount INTEGER NOT NULL,
    phone VARCHAR(20) NOT NULL,
    operator VARCHAR(20) NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'pending',
    failure_reason VARCHAR(300),
    initiated_by BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    settled_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_giving_payment_tx_payment ON giving_payment_transactions(payment_id);
CREATE UNIQUE INDEX idx_giving_payment_tx_ref ON giving_payment_transactions(provider, provider_ref);
-- Au plus une transaction en attente par paiement : pas de double débit.
CREATE UNIQUE INDEX idx_giving_payment_tx_one_pending ON giving_payment_transactions(payment_id) WHERE status = 'pending';
