-- File d'envoi des SMS de notification : écrite dans la même transaction que l'action métier,
-- envoyée en arrière-plan avec nouvelles tentatives (une passerelle lente ou en panne ne bloque plus l'action).
CREATE TABLE platform_sms_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT,
    phone VARCHAR(20) NOT NULL,
    message VARCHAR(480) NOT NULL,
    notification_type VARCHAR(40),
    status VARCHAR(12) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sending', 'sent', 'failed')),
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_error VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_platform_sms_outbox_due ON platform_sms_outbox(next_attempt_at) WHERE status IN ('pending', 'sending');
