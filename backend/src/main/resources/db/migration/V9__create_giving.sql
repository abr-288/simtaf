-- Module giving : panier, demandes de dons, échéances, bénéficiaires, missions, preuves,
-- paiements (dont échanges de services) et litiges. Les références vers les utilisateurs,
-- articles du catalogue et commandes de services sont des identifiants (pas de FK inter-modules).

CREATE TABLE giving_cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    catalog_item_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1 CHECK (quantity BETWEEN 1 AND 500),
    target VARCHAR(150),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_giving_cart_user ON giving_cart_items(user_id);

CREATE TABLE giving_beneficiaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    phone VARCHAR(30),
    zone VARCHAR(100),
    address VARCHAR(200),
    needs VARCHAR(500),
    notes VARCHAR(1000),
    consent BOOLEAN NOT NULL DEFAULT FALSE,
    user_id BIGINT,
    created_by BIGINT,
    archived_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE giving_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ref VARCHAR(40) NOT NULL UNIQUE,
    user_id BIGINT NOT NULL,
    kind VARCHAR(20) NOT NULL DEFAULT 'catalogue',
    title VARCHAR(200) NOT NULL,
    description VARCHAR(2000),
    category VARCHAR(40) NOT NULL DEFAULT 'autre',
    target_name VARCHAR(150),
    target_zone VARCHAR(100),
    beneficiary_id BIGINT,
    partner_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'submitted',
    rejection_reason VARCHAR(1000),
    info_request VARCHAR(1000),
    amount_per_occurrence INTEGER NOT NULL DEFAULT 0,
    occurrences INTEGER NOT NULL DEFAULT 1,
    total_amount INTEGER NOT NULL DEFAULT 0,
    payment_mode VARCHAR(20) NOT NULL DEFAULT 'immediate',
    recurrence VARCHAR(20) NOT NULL DEFAULT 'none',
    start_date TIMESTAMP WITH TIME ZONE,
    annex_services VARCHAR(2000),
    annex_cost INTEGER NOT NULL DEFAULT 0,
    execution_budget INTEGER NOT NULL DEFAULT 0,
    other_fees INTEGER NOT NULL DEFAULT 0,
    idempotency_key VARCHAR(80) UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITH TIME ZONE,
    closed_at TIMESTAMP WITH TIME ZONE,
    archived_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_giving_requests_user ON giving_requests(user_id);
CREATE INDEX idx_giving_requests_status ON giving_requests(status);

CREATE TABLE giving_request_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES giving_requests(id),
    catalog_item_id BIGINT,
    label VARCHAR(200) NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 1,
    unit_price INTEGER NOT NULL DEFAULT 0,
    cost_estimate INTEGER NOT NULL DEFAULT 0,
    target VARCHAR(150)
);
CREATE INDEX idx_giving_items_request ON giving_request_items(request_id);

CREATE TABLE giving_request_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES giving_requests(id),
    status VARCHAR(20) NOT NULL,
    note VARCHAR(2000),
    actor_id BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_giving_history_request ON giving_request_history(request_id);

CREATE TABLE giving_installments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES giving_requests(id),
    seq INTEGER NOT NULL,
    due_date TIMESTAMP WITH TIME ZONE NOT NULL,
    amount INTEGER NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'planned',
    notified_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_giving_installments_request ON giving_installments(request_id);

CREATE TABLE giving_missions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES giving_requests(id),
    provider_id BIGINT,
    title VARCHAR(200) NOT NULL,
    instructions VARCHAR(1500),
    status VARCHAR(20) NOT NULL DEFAULT 'proposed',
    refusal_reason VARCHAR(600),
    due_date TIMESTAMP WITH TIME ZONE,
    provider_fee INTEGER NOT NULL DEFAULT 0,
    compensation_mode VARCHAR(16) NOT NULL DEFAULT 'money',
    exchange_description VARCHAR(600),
    exchange_status VARCHAR(16) DEFAULT 'pending',
    exception_reason VARCHAR(500),
    reassigned_from BIGINT,
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP WITH TIME ZONE,
    validated_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_giving_missions_provider ON giving_missions(provider_id);
CREATE INDEX idx_giving_missions_request ON giving_missions(request_id);

CREATE TABLE giving_proofs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL REFERENCES giving_requests(id),
    mission_id BIGINT,
    type VARCHAR(20) NOT NULL,
    file_key VARCHAR(200) NOT NULL,
    file_name VARCHAR(120) NOT NULL,
    mime VARCHAR(60) NOT NULL,
    size BIGINT NOT NULL DEFAULT 0,
    sha256 VARCHAR(64),
    caption VARCHAR(300),
    uploaded_by BIGINT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    rejection_reason VARCHAR(500),
    reviewed_by BIGINT,
    reviewed_at TIMESTAMP WITH TIME ZONE,
    visible_to_donor BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_giving_proofs_request ON giving_proofs(request_id);
CREATE INDEX idx_giving_proofs_mission ON giving_proofs(mission_id);

CREATE TABLE giving_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT,
    mission_id BIGINT,
    service_order_id BIGINT,
    installment_id BIGINT,
    user_id BIGINT NOT NULL,
    direction VARCHAR(4) NOT NULL,
    kind VARCHAR(16) NOT NULL DEFAULT 'don',
    mode VARCHAR(16) NOT NULL DEFAULT 'money',
    method VARCHAR(20),
    amount_planned INTEGER NOT NULL DEFAULT 0,
    amount_validated INTEGER,
    amount_paid INTEGER NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'planned',
    reference VARCHAR(100),
    receipt_key VARCHAR(200),
    receipt_name VARCHAR(120),
    receipt_mime VARCHAR(60),
    exchange_description VARCHAR(600),
    exchange_status VARCHAR(16),
    due_date TIMESTAMP WITH TIME ZONE,
    note VARCHAR(400),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_giving_payments_request ON giving_payments(request_id);
CREATE INDEX idx_giving_payments_user ON giving_payments(user_id);
CREATE INDEX idx_giving_payments_order ON giving_payments(service_order_id);

CREATE TABLE giving_disputes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ref VARCHAR(40) NOT NULL UNIQUE,
    request_id BIGINT,
    mission_id BIGINT,
    opened_by BIGINT NOT NULL,
    against_user_id BIGINT,
    subject VARCHAR(150) NOT NULL,
    description VARCHAR(2000),
    status VARCHAR(16) NOT NULL DEFAULT 'open',
    responsible_id BIGINT,
    decision VARCHAR(2000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE giving_dispute_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispute_id BIGINT NOT NULL REFERENCES giving_disputes(id),
    author_id BIGINT NOT NULL,
    body VARCHAR(2000) NOT NULL,
    attachment_key VARCHAR(200),
    attachment_name VARCHAR(120),
    attachment_mime VARCHAR(60),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_giving_dispute_messages ON giving_dispute_messages(dispute_id);
