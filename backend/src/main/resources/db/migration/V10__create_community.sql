-- Module community : services communautaires (commandes, négociation) et publications partenaires.
CREATE TABLE community_service_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL,
    provider_id BIGINT NOT NULL,
    offer_id BIGINT,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(1500),
    zone VARCHAR(100),
    proposed_price INTEGER NOT NULL DEFAULT 0,
    agreed_price INTEGER,
    compensation_mode VARCHAR(16) NOT NULL DEFAULT 'money',
    exchange_description VARCHAR(600),
    status VARCHAR(20) NOT NULL DEFAULT 'requested',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_community_orders_client ON community_service_orders(client_id);
CREATE INDEX idx_community_orders_provider ON community_service_orders(provider_id);

CREATE TABLE community_service_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES community_service_orders(id),
    author_id BIGINT NOT NULL,
    body VARCHAR(1000) NOT NULL,
    price INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_community_messages_order ON community_service_messages(order_id);

CREATE TABLE community_listings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT NOT NULL,
    type VARCHAR(20) NOT NULL,
    title VARCHAR(150) NOT NULL,
    description VARCHAR(2000),
    zone VARCHAR(100),
    goal_amount INTEGER NOT NULL DEFAULT 0,
    raised_amount INTEGER NOT NULL DEFAULT 0,
    mena_support INTEGER NOT NULL DEFAULT 0,
    ends_at TIMESTAMP WITH TIME ZONE,
    status VARCHAR(16) NOT NULL DEFAULT 'pending',
    rejection_reason VARCHAR(400),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_community_listings_owner ON community_listings(owner_id);
CREATE INDEX idx_community_listings_status ON community_listings(status);

CREATE TABLE community_listing_contributions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES community_listings(id),
    user_id BIGINT NOT NULL,
    amount INTEGER NOT NULL CHECK (amount > 0),
    method VARCHAR(20),
    reference VARCHAR(100),
    status VARCHAR(16) NOT NULL DEFAULT 'declared',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_community_contributions_listing ON community_listing_contributions(listing_id);
