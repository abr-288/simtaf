CREATE TABLE rewards_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    amount INTEGER NOT NULL,
    type VARCHAR(20) NOT NULL,
    event_key VARCHAR(60),
    reason VARCHAR(300),
    ref_type VARCHAR(40),
    ref_id BIGINT,
    ref_key VARCHAR(200) UNIQUE,
    status VARCHAR(16) NOT NULL DEFAULT 'approved',
    created_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_rewards_tx_user ON rewards_transactions(user_id, id DESC);
CREATE INDEX idx_rewards_tx_status ON rewards_transactions(status);

-- Réalisations comptées pour les badges (une ligne par objet, anti-doublon).
CREATE TABLE rewards_achievements (
    ref_key VARCHAR(200) PRIMARY KEY,
    user_id BIGINT NOT NULL,
    kind VARCHAR(40) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_rewards_achievements_user ON rewards_achievements(user_id, kind);

CREATE TABLE rewards_badges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    code VARCHAR(40) NOT NULL,
    awarded_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_rewards_badges UNIQUE (user_id, code)
);

CREATE TABLE rewards_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(20) NOT NULL,
    ref_id BIGINT NOT NULL,
    from_user_id BIGINT NOT NULL,
    to_user_id BIGINT NOT NULL,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment VARCHAR(800),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_rewards_reviews UNIQUE (kind, ref_id, from_user_id)
);
CREATE INDEX idx_rewards_reviews_to ON rewards_reviews(to_user_id);
