CREATE TABLE menewa_catalog_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug VARCHAR(180) NOT NULL UNIQUE,
    title VARCHAR(120) NOT NULL,
    category VARCHAR(40) NOT NULL,
    kind VARCHAR(20) NOT NULL DEFAULT 'don',
    description VARCHAR(1000),
    unit_price INTEGER NOT NULL CHECK (unit_price >= 0),
    cost_estimate INTEGER NOT NULL DEFAULT 0 CHECK (cost_estimate >= 0),
    unit VARCHAR(30) NOT NULL DEFAULT 'unité',
    emoji VARCHAR(12) DEFAULT '🎁',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_menewa_catalog_category_title ON menewa_catalog_items(category, title);
CREATE INDEX idx_menewa_catalog_active ON menewa_catalog_items(active);
